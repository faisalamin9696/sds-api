function methodDoc(meta: SDSMethodMeta): string[] {
  const callback = callbackNameOf(meta);
  const lines: string[] = ['/**'];
  const description = meta.description ?? 'No description available.';
  for (const line of description.split('\n')) lines.push(` * ${line.replace(/\*\//g, '*\\/')}`);
  lines.push(' *');
  lines.push(` * @param ${callback} node style callback \`(error, result) => void\``);
  if (meta.params.length) {
    lines.push(' *');
    lines.push(' * Parameters (positional, in route order):');
    for (const param of meta.params) {
      lines.push(
        ` * - \`${param.name}\` (${param.optional ? 'optional' : 'required'}) — ${paramDoc(param)}`,
      );
    }
  }
  lines.push(' *');
  lines.push(` * @see ${sourceBase}/describeMethod/${meta.module}.${meta.name}`);
  lines.push(' */');
  return lines;
}

function signatureLines(meta: SDSMethodMeta, argsName: string): string[] {
  const prop = propertyName(meta.name);
  const callback = callbackNameOf(meta);
  const result = resultTsType(meta.result);
  const params = meta.params;
  const allOptional = params.every((param) => param.optional);
  const lines: string[] = [];
  const push = (signature: string): void => {
    lines.push(`  ${signature}`);
  };

  if (params.length === 0) {
    push(`${prop}<T = ${result}>(${callback}: Callback<T>): Promise<void>;`);
    push(`${prop}<T = ${result}>(): Promise<T>;`);
    return lines;
  }

  if (allOptional) {
    push(`${prop}<T = ${result}>(${callback}: Callback<T>): Promise<void>;`);
  }

  push(`/** Object style with callback. */`);
  push(`${prop}<T = ${result}>(args: ${argsName}, ${callback}: Callback<T>): Promise<void>;`);
  push(`/** Object style, promise. */`);
  push(`${prop}<T = ${result}>(args: ${argsName}): Promise<T>;`);

  // TS forbids a required parameter after an optional one, so the callback
  // variant declares optional parameters as `type | undefined` instead of `?`.
  const withCallback = params
    .map((param, index) => {
      const name = positionalName(param.name, index);
      const type = tsType(param);
      return param.optional ? `${name}: ${type} | undefined` : `${name}: ${type}`;
    })
    .join(', ');
  push(`${prop}<T = ${result}>(${withCallback}, ${callback}: Callback<T>): Promise<void>;`);

  const lastRequired = params.reduce((last, param, index) => (param.optional ? last : index), -1);
  const plain = params
    .map((param, index) => {
      const name = positionalName(param.name, index);
      const type = tsType(param);
      if (param.optional && index > lastRequired) return `${name}?: ${type}`;
      return `${name}: ${type}${param.optional ? ' | undefined' : ''}`;
    })
    .join(', ');
  push(`${prop}<T = ${result}>(${plain}): Promise<T>;`);

  return lines;
}

function argsInterface(method: SDSMethodMeta, interfaceName: string): string[] {
  const lines: string[] = [
    `/** Object style arguments of \`${method.module}.${method.name}\`. */`,
    `export interface ${interfaceName} {`,
  ];
  for (const param of method.params) {
    lines.push(`  /** ${paramDoc(param)} */`);
    lines.push(`  ${propertyName(param.name)}${param.optional ? '?' : ''}: ${tsType(param)};`);
  }
  lines.push('}');
  return lines;
}

