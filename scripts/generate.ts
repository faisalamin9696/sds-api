  out.push('## Mapping responses with `mapSds`');
  out.push('');
  out.push('Many SDS list/search methods return a **column oriented table** instead of objects:');
  out.push('');
  out.push('```json');
  out.push('{');
  out.push('  "cols": { "link_id": 0, "author": 6, "permlink": 7 },');
  out.push('  "rows": [[114136936, 0, 69.305, 0, "", "", "alice", "hello"]]');
  out.push('}');
  out.push('```');
  out.push('');
  out.push('`mapSds()` converts that into plain row objects — and passes every other payload');
  out.push('(plain JSON, arrays, raw `{ code, result }` envelopes) through unchanged:');
  out.push('');
  out.push('```ts');
  out.push("import { mapSds, isSDSTable } from '@steempro/sds';");
  out.push('');
  out.push("const feed = await sds.feeds.getActivePostsByCreated({ limit: 1 });");
  out.push('const rows = mapSds(feed);');
  out.push('// [ { link_id: 114136936, author: \'alice\', permlink: \'hello\', … }, … ]');
  out.push('');
  out.push('// …or straight from the promise:');
  out.push('const rows2 = await sds.feeds');
  out.push("  .getActivePostsByCreated({ limit: 1 })");
  out.push('  .then(mapSds);');
  out.push('');
  out.push('// Narrow first if the payload type is unknown:');
  out.push('const payload: unknown = await sds.request(\'/feeds_api/getActivePostsByTrending\');');
  out.push('const rows3 = isSDSTable(payload) ? mapSds(payload) : payload;');
  out.push('```');
  out.push('');
  out.push('Implementation:');
  out.push('');
  out.push('```ts');
  out.push('export function mapSds(data: SDSTable): SDSRow[];');
  out.push('export function mapSds<T = any>(data: unknown): T;');
  out.push('');
  out.push('export function mapSds(data: unknown): unknown {');
  out.push('  const payload = unwrapEnvelope(data);          // { code, result } → result');
  out.push('  if (!isSDSTable(payload)) return payload;      // not a table → unchanged');
  out.push('');
  out.push('  const cols = payload.cols;                     // { name: index } or [name, …]');
  out.push('  const rows = payload.rows ?? [];');
  out.push('  const names = Array.isArray(cols) ? cols : Object.keys(cols);');
  out.push('');
  out.push('  return rows.map((row) => {');
  out.push('    if (Array.isArray(row)) {');
  out.push('      const out = {};');
  out.push('      names.forEach((name, position) => {');
  out.push('        out[name] = row[Array.isArray(cols) ? position : cols[name]];');
  out.push('      });');
  out.push('      return out;                               // positional row → keyed object');
  out.push('    }');
  out.push('    if (row && typeof row === "object") return { ...row };');
  out.push('    return { [names[0]]: row };                 // scalar row of a 1-column table');
  out.push('  });');
  out.push('}');
  out.push('```');
