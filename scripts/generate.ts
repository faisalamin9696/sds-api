  out.push('  UTC and 12+ digit numbers are read as milliseconds. Values that cannot be parsed');
  out.push('  throw an `SDSValidationError` listing the accepted formats instead of silently');
  out.push('  returning empty or "now" data.');
  out.push('- Client side validation (`validate: true`) rejects bad types, out-of-range values and');
