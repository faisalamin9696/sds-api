/**
 * Sample community id used in generated examples — every community parameter
 * is a `hive-` prefixed hivemind account (verified against all 3112 live
 * communities; bare ids/titles/accounts answer with empty results).
 */
const COMMUNITY_ID_SAMPLE = 'hive-160125';

/** Property access, dotted names use bracket notation (`sds.x["get.ticker"]`). */
function accessor(name: string): string {
  return isValidIdentifier(name) && !RESERVED.has(name)
    ? `.${name}`
    : `[${JSON.stringify(name)}]`;
}

function coerceScalar(type: string, raw: string): unknown {
  const normalized = type.trim().toLowerCase();
  if (normalized === 'int' || normalized === 'float' || normalized === 'number') {
    const number = Number(raw);
    return Number.isFinite(number) ? number : raw;
  }
  if (normalized === 'bool' || normalized === 'boolean') return raw === 'true' || raw === '1';
  if (normalized.startsWith('json')) {
    try {
      return JSON.parse(raw);
    } catch {
      return raw;
    }
  }
  return raw;
}

/** Sample value for a documented field of a structured parameter. */
function sampleField(field: SDSFieldMeta): unknown {
  if (field.default !== undefined && field.default !== 'null') {
    return coerceScalar(field.type, field.default);
  }
  const type = field.type.trim().toLowerCase();
  if (isTimestampParam(field)) {
    // Keep `fromTime` before `toTime` so generated ranges stay sane.
    const leaf = (field.name.split('.').pop() ?? field.name).toLowerCase();
    return timestampSample(leaf.startsWith('to') ? 1 : 0);
  }
  if (type === 'int' || type === 'float' || type === 'number') return 10;
  if (type === 'bool' || type === 'boolean') return true;
  if (type === 'account_name') return isCommunityParam(field) ? COMMUNITY_ID_SAMPLE : 'alice';
  if (type === 'fixed_value') return field.allowedValues?.[0] ?? 'value';
  if (type.startsWith('json_object')) return {};
  if (type.startsWith('json_array')) return [];
  if (field.fields?.length) return sampleFields(field.fields);
  return 'example';
}

/** Builds a nested sample object from the documented (dotted) field paths. */
function sampleFields(fields: SDSFieldMeta[]): Record<string, unknown> {
  const root: Record<string, unknown> = {};
  for (const field of fields) {
    const parts = field.name.split('.');
    let node = root;
    for (const part of parts.slice(0, -1)) {
      if (typeof node[part] !== 'object' || node[part] === null) node[part] = {};
      node = node[part] as Record<string, unknown>;
    }
    node[parts[parts.length - 1]] = sampleField(field);
  }
  return root;
}

/**
 * Sample value of a structured parameter built from its documented fields.
 *
 * Documented paths are prefixed with the parameter name (`query.type` for the
 * `query` parameter); the prefix is dropped because the JSON payload itself
 * only contains the inner structure (`{ "type": … }`).
 */
function sampleJson(param: SDSParamMeta): Record<string, unknown> {
  const prefix = `${param.name}.`;
  const fields = (param.fields ?? []).map((field) =>
    field.name.startsWith(prefix) ? { ...field, name: field.name.slice(prefix.length) } : field,
  );
  return sampleFields(fields);
}

/**
 * Fixed base day of generated timestamp examples — deterministic docs.
 * `2020-09-13` is unix `1599961600`; `1600000000` (used in prose) is
 * `2020-09-13T12:26:40Z`.
 */
const TIMESTAMP_SAMPLE_DAY = Date.UTC(2020, 8, 13);

/** Sample timestamp as a date string, `days` after the base day. */
const timestampSample = (days: number): string =>
  new Date(TIMESTAMP_SAMPLE_DAY + days * 86_400_000).toISOString().slice(0, 10);

/** Plausible sample value for a parameter (documented default when available). */
function sampleValue(param: SDSParamMeta, index: number): unknown {
  const type = param.type.trim().toLowerCase();

  if (param.default !== undefined && param.default !== 'null') {
    return coerceScalar(param.type, param.default);
  }
  if (type === 'account_name') return isCommunityParam(param) ? COMMUNITY_ID_SAMPLE : 'alice';
  if (type.startsWith('hex_string')) return '0'.repeat(40);
  if (isTimestampParam(param)) return timestampSample(index);
  if (type === 'int' || type === 'float' || type === 'number') {
    let value = 10 + index;
    if (param.min !== undefined && value < param.min) value = param.min;
    if (param.max !== undefined && value > param.max) value = param.max;
    return value;
  }
  if (type === 'bool' || type === 'boolean') return true;
  if (type === 'fixed_value') return param.allowedValues?.[0] ?? 'value';
  if (type === 'fixed_csv') return param.allowedValues?.slice(0, 2).join(',') ?? 'value';
  if (type === 'int_csv') return '1,2';
  if (type === 'account_name_csv') return 'alice,bob';
  if (type.endsWith('_csv') || type === 'csv') return 'value1,value2';
  if (type.startsWith('json')) return sampleJson(param);
  return 'example';
}

/** Sample values for every parameter of a method (positional, route order). */
function sampleArgs(meta: SDSMethodMeta): unknown[] {
  return meta.params.map((param, index) => sampleValue(param, index));
}

/** TypeScript literal of a sample value (`{ fromTime: 0 }`, `'alice'`, …). */
function tsLiteral(value: unknown): string {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) return `[${value.map(tsLiteral).join(', ')}]`;
  if (value && typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>);
    if (!entries.length) return '{}';
    const body = entries
      .map(([key, entry]) => `${isValidIdentifier(key) && !RESERVED.has(key) ? key : JSON.stringify(key)}: ${tsLiteral(entry)}`)
      .join(', ');
    return `{ ${body} }`;
  }
  return 'null';
}

/** Example request URL for a method (documented defaults filled in). */
function exampleUrl(meta: SDSMethodMeta): string | undefined {
  try {
    const segments = resolveSegments(meta, sampleArgs(meta), { validate: true }).map((segment) =>
      encodeURIComponent(segment),
    );
    return `${sourceBase}${buildPath(meta.path, segments)}`;
  } catch {
    return undefined;
  }
}

/** Compact overload signatures (JSDoc comment lines stripped, dedented). */
function docSignature(meta: SDSMethodMeta, argsName: string): string[] {
  return signatureLines(meta, argsName)
    .filter((line) => !line.trim().startsWith('/**'))
    .map((line) => line.trim());
}

