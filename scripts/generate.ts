const BANNER = `/* eslint-disable */
/**
 * AUTO-GENERATED FILE — DO NOT EDIT.
 *
 * Generated by \`npm run generate\` from the SDS API Reference.
 * Re-run \`npm run scrape && npm run generate\` to refresh it.
 */`;

/** Repository of this package (linked from every generated document). */
const REPO_URL = 'https://github.com/faisalamin9696/sds';
/** Human readable repository link text. */
const REPO_NAME = 'github.com/faisalamin9696/sds';

let sourceBase = 'https://sds0.steemworld.org';

/* ------------------------------------------------------------------ */
/* naming helpers                                                      */
/* ------------------------------------------------------------------ */

const RESERVED = new Set([
  'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete', 'do',
  'else', 'enum', 'export', 'extends', 'false', 'finally', 'for', 'function', 'if', 'implements',
  'import', 'in', 'instanceof', 'interface', 'let', 'new', 'null', 'package', 'private', 'protected',
  'public', 'return', 'static', 'super', 'switch', 'this', 'throw', 'true', 'try', 'typeof', 'var',
  'void', 'while', 'with', 'yield', 'await',
]);

const isValidIdentifier = (name: string): boolean => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name);

/** Property name inside an interface (`condenser_api.get_ticker` → quoted). */
const propertyName = (name: string): string =>
  isValidIdentifier(name) && !RESERVED.has(name) ? name : JSON.stringify(name);

/** Positional parameter name (must be a legal identifier that is not `callback`). */
function positionalName(name: string, index: number): string {
  if (!isValidIdentifier(name)) return `arg${index}`;
  if (RESERVED.has(name)) return `${name}$`;
  if (name === 'callback' || name === 'done') return `${name}$`;
  return name;
}

/** `getOpsInBlock` → `GetOpsInBlock`, `condenser_api.get_ticker` → `CondenserApiGetTicker`. */
function pascal(name: string): string {
  const joined = name
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
  return /^[0-9]/.test(joined) ? `_${joined}` : joined;
}

function allowedList(values: string[] | undefined, max = 6): string {
  if (!values?.length) return '';
  const shown = values.slice(0, max).join(' | ');
  return values.length > max ? `${shown} | … (${values.length} values)` : shown;
}

/** Callback parameter name (must not collide with a route parameter). */
const callbackNameOf = (meta: SDSMethodMeta): string =>
  meta.params.some((param) => param.name === 'callback') ? 'done' : 'callback';

/** Object style arguments interface of a method (unique per module). */
const argsNameOf = (moduleKey: string, method: SDSMethodMeta): string =>
  `${pascal(moduleKey)}${pascal(method.name)}Args`;

