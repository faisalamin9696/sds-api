function tsType(param: SDSParamMeta): string {
  const type = param.type.trim().toLowerCase();

  if (type === 'int' || type === 'float' || type === 'number') {
    // Timestamp parameters accept any date form — the client converts it to
    // unix seconds before the request is sent (see `isTimestampParam`).
    return type === 'int' && isTimestampParam(param) ? 'number | string | Date' : 'number';
  }
  if (type === 'bool' || type === 'boolean') return 'boolean';
  if (type.startsWith('hex_string')) return 'string';
  if (type === 'account_name') return 'string';

  if (type === 'fixed_value') {
    if (param.allowedValues?.length) {
      return param.allowedValues.map((value) => JSON.stringify(value)).join(' | ');
    }
    return 'string';
  }

  if (type === 'fixed_csv') {
    // The value lists are long (up to ~80 entries), so a plain string/list is
    // used here — the documented values are kept in the JSDoc and in the
    // metadata (`describeMethod()`).
    return 'string | string[]';
  }

  if (type === 'account_name_csv') return 'string | string[]';
  if (type === 'int_csv') return 'string | number | Array<string | number>';
  if (type.startsWith('json_object')) return 'SDSJsonObject | string';
  if (type.startsWith('json_array')) return 'SDSJsonArray | string';
  if (type.startsWith('json')) return 'unknown';
  return 'string';
}

function resultTsType(result: string | undefined): string {
  switch ((result ?? '').trim().toLowerCase()) {
    case 'json object':
      return 'SDSJsonObject';
    case 'json array':
      return 'SDSJsonArray';
    case 'integer':
      return 'number';
    case 'string':
      return 'string';
    case 'boolean':
      return 'boolean';
    default:
      return 'any';
  }
}

function paramDoc(param: SDSParamMeta): string {
  const parts = [param.type];
  if (isCommunityParam(param)) parts.push(`hive community id, e.g. \`hive-160125\``);
  if (isTimestampParam(param))
    parts.push('timestamp — accepts `Date`, date string or unix seconds (12+ digit numbers are read as ms)');
  if (param.default !== undefined) parts.push(`default \`${param.default}\``);
  if (param.min !== undefined && param.max !== undefined) parts.push(`${param.min}…${param.max}`);
  else if (param.min !== undefined) parts.push(`min ${param.min}`);
  else if (param.max !== undefined) parts.push(`max ${param.max}`);
  const allowed = allowedList(param.allowedValues, 4);
  if (allowed) parts.push(`one of: ${allowed}`);
  if (param.fields?.length) parts.push(`${param.fields.length} documented fields`);
  return parts.join(' · ');
}

function rangeText(param: SDSParamMeta): string {
  if (param.min !== undefined && param.max !== undefined) return `${param.min} – ${param.max}`;
  if (param.min !== undefined) return `≥ ${param.min}`;
  if (param.max !== undefined) return `≤ ${param.max}`;
  return '';
}

/** Type cell of a parameter table — flags hive community ids and timestamps. */
function typeCell(param: SDSParamMeta): string {
  if (isCommunityParam(param)) return `${param.type} (e.g. \`${COMMUNITY_ID_SAMPLE}\`)`;
  if (isTimestampParam(param)) return `${param.type} (Date / date string / seconds)`;
  return param.type;
}

