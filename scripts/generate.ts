async function main(): Promise<void> {
  const reference: SDSApiReference = JSON.parse(
    await readFile(path.join(root, 'data', 'api.json'), 'utf8'),
  );
  sourceBase = reference.source;

  await mkdir(path.join(root, 'src', 'generated'), { recursive: true });
  await mkdir(path.join(root, 'docs'), { recursive: true });

  await writeFile(path.join(root, 'src', 'generated', 'meta.ts'), generateMeta(reference), 'utf8');
  await writeFile(path.join(root, 'src', 'generated', 'types.ts'), generateTypes(reference), 'utf8');
  await writeFile(path.join(root, 'docs', 'METHODS.md'), generateDocs(reference), 'utf8');
  await writeFile(path.join(root, 'documentation.md'), generateDocumentation(reference), 'utf8');

  const methodCount = reference.modules.reduce((sum, module) => sum + module.methods.length, 0);
  console.log(
    `Generated src/generated/{meta,types}.ts, docs/METHODS.md and documentation.md — ` +
      `${reference.modules.length} modules, ${methodCount} methods (reference v${reference.version})`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
