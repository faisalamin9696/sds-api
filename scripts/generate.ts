  out.push('}');
  out.push('');
  out.push('// Callback style delivers the same errors instead of throwing:');
  out.push("sds.posts.getPost('alice', 'missing', (error, post) => {");
  out.push('  if (error) return console.error(error.code, error.message);');
  out.push('  console.log(post);');
  out.push('});');
  out.push('```');
  out.push('');
  out.push('Retries: network failures, timeouts, HTTP 5xx and 429 are retried with exponential');
  out.push('backoff (`retries`, `retryDelay`, overridable per call). Application errors are never retried.');
  out.push('');

  out.push('## Introspection');
  out.push('');
  out.push('```ts');
  out.push('sds.listModules();                                 // all modules');
  out.push("sds.listMethods('chain_api');                      // methods of one module");
  out.push("sds.describeMethod('chain_api.getAccountNames');   // path, params, defaults, result");
  out.push("sds.hasMethod('posts_api', 'getPost');            // true");
  out.push("sds.module('chain_api');                          // → sds.chain namespace");
  out.push('sds.referenceVersion;                             // bundled reference version');
  out.push('');
  out.push("import { listModules, listMethods, findMethod, API_REFERENCE } from '@steempro/sds';");
  out.push('```');
  out.push('');

