function generateMeta(reference: SDSApiReference): string {
  return `${BANNER}
import type { SDSModuleMeta } from '../meta-types';

/** Instance the metadata was scraped from. */
export const SDS_REFERENCE_SOURCE = ${JSON.stringify(reference.source)};

/** Version of the SDS API reference the metadata was scraped from. */
export const SDS_REFERENCE_VERSION = ${JSON.stringify(reference.version)};

/** Date of the scrape. */
export const SDS_REFERENCE_DATE = ${JSON.stringify(reference.scrapedAt)};

/** All SDS modules with their methods, in reference order. */
export const SDS_MODULES: SDSModuleMeta[] = ${JSON.stringify(reference.modules, null, 2)};
`;
}

function generateTypes(reference: SDSApiReference): string {
  const out: string[] = [
    BANNER,
    '',
    "import type { Callback } from '../types';",
    '',
    '/** Result payload of methods documented as `JSON Object`. */',
    'export type SDSJsonObject = Record<string, any>;',
    '',
    '/** Result payload of methods documented as `JSON Array`. */',
    'export type SDSJsonArray = any[];',
  ];

  const moduleMap: string[] = [];
  const moduleKeys: string[] = [];
  const namespaces: string[] = [];

  for (const module of reference.modules) {
    const interfaceName = `${pascal(module.key)}Api`;
    const seenMethods = new Set<string>();
    const seenArgs = new Set<string>();
    const members: string[] = [];

    for (const method of module.methods) {
      if (seenMethods.has(method.name)) {
        throw new Error(`Duplicate method ${module.id}.${method.name}`);
      }
      seenMethods.add(method.name);

      if (method.params.length) {
        const argsName = argsNameOf(module.key, method);
        if (seenArgs.has(argsName)) {
          throw new Error(`Duplicate arguments interface ${argsName}`);
        }
        seenArgs.add(argsName);
        out.push('');
        out.push(...argsInterface(method, argsName));
      }

      members.push('');
      members.push(...methodDoc(method).map((line) => `  ${line}`));
      members.push(...signatureLines(method, argsNameOf(module.key, method)));
    }

    out.push('');
    out.push(`/** Module \`${module.id}\` (group: ${module.group}). */`);
    out.push(`export interface ${interfaceName} {`);
    out.push(...members);
    out.push('}');
    out.push('');

    moduleMap.push(`  ${JSON.stringify(module.id)}: ${interfaceName};`);
    moduleKeys.push(`  ${JSON.stringify(module.id)}: ${JSON.stringify(module.key)};`);
    namespaces.push(`  /** \`${module.id}\` */`, `  ${module.key}: ${interfaceName};`);
  }

  out.push('/** Map of SDS module id → module interface. */');
  out.push('export interface SDSModuleMap {');
  out.push(...moduleMap);
  out.push('}');
  out.push('');
  out.push('/** Map of SDS module id → namespace key on the client. */');
  out.push('export interface SDSModuleKeys {');
  out.push(...moduleKeys);
  out.push('}');
  out.push('');
  out.push('/** Module namespaces exposed by the client (`sds.chain`, `sds.posts`, …). */');
  out.push('export interface SDSModules {');
  out.push(...namespaces);
  out.push('}');
  out.push('');

  return out.join('\n');
}

function generateDocs(reference: SDSApiReference): string {
  const methodCount = reference.modules.reduce((sum, module) => sum + module.methods.length, 0);
  const out: string[] = [];

  out.push('# SDS Method Reference');
  out.push('');
  out.push(
    `Generated from [\`${reference.source}\`](${reference.source}) — reference version \`${reference.version}\`, ${reference.modules.length} modules, ${methodCount} methods. ` +
      `Source: [${REPO_NAME}](${REPO_URL}).`,
  );
  out.push('');
  out.push('| Module | Namespace | Group | Methods |');
  out.push('| --- | --- | --- | --- |');
  for (const module of reference.modules) {
    out.push(
      `| [\`${module.id}\`](#${module.id}) | \`sds.${module.key}\` | ${module.group} | ${module.methods.length} |`,
    );
  }
  out.push('');

  for (const module of reference.modules) {
    out.push('---');
    out.push('');
    out.push(`## \`${module.id}\``);
    out.push('');
    out.push(
      `Namespace: \`sds.${module.key}\` · Group: ${module.group} · ${module.methods.length} methods`,
    );
    out.push('');

    for (const method of module.methods) {
      out.push(`### \`sds.${module.key}.${method.name}()\``);
      out.push('');
      out.push(method.description || '_No description available._');
      out.push('');
      out.push(`- Route: \`${method.path}\``);
      if (method.result) out.push(`- Result: ${method.result}`);
      if (method.maxLimit !== undefined) out.push(`- Max. limit: ${method.maxLimit}`);
      if (method.example) out.push(`- Example: \`${method.example}\``);
      out.push('');

      if (method.params.length) {
        out.push('| Parameter | Type | Required | Default | Range | Allowed values |');
        out.push('| --- | --- | --- | --- | --- | --- |');
        for (const param of method.params) {
          out.push(
            `| \`${param.name}\` | ${typeCell(param)} | ${param.optional ? 'no' : 'yes'} | ${
              param.default !== undefined ? `\`${param.default}\`` : '—'
            } | ${rangeText(param) || '—'} | ${
              param.allowedValues?.length ? allowedList(param.allowedValues, 8) : '—'
            } |`,
          );
        }
        out.push('');
      } else {
        out.push('_No parameters._');
        out.push('');
      }
    }
  }

  out.push('');
  return out.join('\n');
}

