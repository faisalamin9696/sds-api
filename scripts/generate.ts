/**
 * GitHub style anchor for a heading (used by the method index links).
 *
 * Matches GitHub's slugger: lowercase, drop everything but word characters,
 * hyphens and spaces, then turn *each* space into a hyphen (spaces are not
 * collapsed, so `Initialization & instances` → `initialization--instances`).
 */
function anchor(text: string): string {
  return text
    .toLowerCase()
    .replace(/`/g, '')
    .replace(/[^\w\- ]+/g, '')
    .trim()
    .replace(/ /g, '-');
}

/** Paragraphs of a description (blank line separated), indented for lists. */
function descriptionLines(description: string | undefined, indent = ''): string[] {
  if (!description) return [`${indent}_No description available._`];
  return description
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.replace(/\s*\n\s*/g, ' ').trim())
    .filter(Boolean)
    .flatMap((paragraph, index) => (index === 0 ? [`${indent}${paragraph}`] : ['', `${indent}${paragraph}`]));
}

/** The generated implementation signature block of a method. */
function implementationBlock(meta: SDSMethodMeta, argsName: string): string[] {
  const lines: string[] = ['```ts'];
  if (meta.params.length) {
    lines.push(`interface ${argsName} {`);
    for (const param of meta.params) {
      lines.push(`  ${propertyName(param.name)}${param.optional ? '?' : ''}: ${tsType(param)};  // ${paramDoc(param)}`);
    }
    lines.push('}');
    lines.push('');
  }
  lines.push(...docSignature(meta, argsName));
  lines.push('```');
  return lines;
}

/** Runnable promise/callback/object style examples of a call. */
function usageExamples(meta: SDSMethodMeta, moduleKey: string): string[] {
  const call = `sds.${moduleKey}${accessor(meta.name)}`;
  const args = sampleArgs(meta);
  const positional = args.map(tsLiteral).join(', ');
  const objectStyle =
    meta.params.length > 0
      ? `{ ${meta.params.map((param, index) => `${propertyName(param.name)}: ${tsLiteral(args[index])}`).join(', ')} }`
      : undefined;

  const lines: string[] = ['```ts'];

  // Promise style (positional).
  if (meta.params.length === 0) {
    lines.push(`const result = await ${call}();`);
  } else {
    lines.push(`const result = await ${call}(${positional});`);
  }

  // Object style, shown as a commented alternative (same scope, no redeclaration).
  if (objectStyle && objectStyle !== positional) {
    lines.push(`// …or object style:`);
    lines.push(`// const result = await ${call}(${objectStyle});`);
  }

  // Callback style.
  if (meta.params.length === 0) {
    lines.push(`${call}((error, result) => {`);
  } else {
    lines.push(`${call}(${positional}, (error, result) => {`);
  }
  lines.push('  if (error) return console.error(error.code, error.message);');
  lines.push('  console.log(result);');
  lines.push('});');

  // Generic entry point.
  lines.push('');
  if (meta.params.length === 0) {
    lines.push(`await sds.call('${meta.module}', '${meta.name}');`);
  } else {
    lines.push(`await sds.call('${meta.module}', '${meta.name}', ${positional ? `[${positional}]` : '[]'});`);
  }
  lines.push('```');
  return lines;
}

