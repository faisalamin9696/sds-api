  out.push('| `SDSHttpError` | `ERR_SDS_HTTP` | Non-success HTTP status (`error.status`, `error.body`) |');
  out.push('| `SDSResponseError` | `ERR_SDS_RESPONSE` | HTTP 200 but not the expected JSON envelope |');
  out.push('| `SDSApiError` | `ERR_SDS_API` | Application error `{ code: -1, error }` (`error.apiCode`) |');
  out.push('');
  out.push('```ts');
  out.push("import { SDSApiError, isSDSError } from '@steempro/sds';");
  out.push('');
  out.push('try {');
  out.push("  await sds.posts.getPost('alice', 'missing');");
